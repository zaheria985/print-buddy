"""[printer] slicer: OrcaSlicer by default, Bambu Studio only where the vendor profile allows it (opt-in)."""
import copy
from pathlib import Path

import pytest

from print_buddy import printers, settings
from print_buddy.core import orca_adapter as adapter
from print_buddy.printers.base import PrinterModel
from print_buddy.printers.klipper.adapter import KlipperAdapter
from .test_orca_adapter import _allow_post, _source, _state

KEY = "bambulab.zz_test_printer"


def bambu_adapter(monkeypatch, slicer):
    model = PrinterModel(key=KEY, label="Test Bambu", adapter=KlipperAdapter, templates="klipper_generic",
                         vendor=printers.VENDORS["bambulab"], supported_nozzle_sizes=(0.4,), settings={})
    monkeypatch.setitem(printers.MODELS, KEY, model)
    cfg = copy.deepcopy(settings.current())
    cfg["printer"].update(model=KEY, vendor="bambulab", slicer=slicer)
    cfg["orca"]["templates"] = settings.ROOT / "print_buddy" / "templates" / "orca" / "klipper_generic"
    return printers.get(KEY, cfg)


def fake_run(calls, text="; generated by BambuStudio 2.8.2\nG90\nG1 X1 Y1 Z0.2\n"):
    def run(command, **_kwargs):
        calls.append(command)
        output = Path(command[command.index('--outputdir') + 1]) / 'plate_1.gcode'
        generator = text if 'com.bambulab.BambuStudio' in command else text.replace('BambuStudio', 'OrcaSlicer')
        output.write_text(generator)
        return type('R', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()
    return run


def test_existing_printers_slice_with_orca():
    for key in ("flashforge.ad5x", "sovol.sv06", "klipper.generic", "octoprint.marlin"):
        assert adapter.slicer_choice(printers.get(key)) == "orca"


def test_bambu_studio_primary_runs_once_and_is_not_a_fallback(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    calls = []
    monkeypatch.setattr(adapter.subprocess, 'run', fake_run(calls))
    printer = bambu_adapter(monkeypatch, "bambu_studio")
    output, provenance, configs = adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)
    assert len(calls) == 1 and 'com.bambulab.BambuStudio' in calls[0]
    assert '--unshare=network' in calls[0]  # the configured Flathub command keeps its network cut
    assert provenance['slicer'] == 'Bambu Studio' and provenance['fallback'] is None
    assert any(path.parent.name == 'bambu' for path in configs)
    assert not (tmp_path / 'out' / 'orca.log').exists()


def test_bambu_vendor_with_orca_runs_orca(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    calls = []
    monkeypatch.setattr(adapter.subprocess, 'run', fake_run(calls))
    printer = bambu_adapter(monkeypatch, "orca")
    _output, provenance, _ = adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)
    assert len(calls) == 1 and 'com.orcaslicer.OrcaSlicer' in calls[0]
    assert provenance['slicer'] == 'OrcaSlicer'


def test_klipper_start_code_in_bambu_output_is_blocked_after_slicing(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    calls = []
    text = "; generated by BambuStudio 2.8.2\nPRINT_START BED=60 HOTEND=215\nG1 X1 Y1 Z0.2\n"
    monkeypatch.setattr(adapter.subprocess, 'run', fake_run(calls, text))
    printer = bambu_adapter(monkeypatch, "bambu_studio")
    with pytest.raises(RuntimeError, match="Post-slice guard blocked: .*non-Bambu commands.*PRINT_START"):
        adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)


def test_bambu_studio_failure_names_its_own_log(tmp_path, monkeypatch):
    _allow_post(monkeypatch)

    def run(command, **_kwargs):
        return type('R', (), {'returncode': 3, 'stdout': '', 'stderr': 'boom'})()
    monkeypatch.setattr(adapter.subprocess, 'run', run)
    printer = bambu_adapter(monkeypatch, "bambu_studio")
    with pytest.raises(RuntimeError, match=r"Bambu Studio is the configured slicer; Bambu Studio failed \(3\)") as exc:
        adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state(), adapter=printer)
    assert 'orca.log' not in str(exc.value) and 'bambu.log' in str(exc.value)
