from pathlib import Path
import json
import struct
import sys
from unittest.mock import patch

from print_buddy.core import orca_adapter as adapter
from print_buddy.core import model_job as job


def _state():
    import copy
    state = copy.deepcopy(job.printer_state.load())
    state['ifs_slots'] = {'1': {'slot': 1, 'spoolman_id': 1, 'material': 'PLA',
                                'physical_color_verified': True, 'hex': 'FFFFFF'}}
    state['spool'].update(spoolman_id=1, material='PLA', density=1.24)
    return state


def _source(tmp_path):
    source = tmp_path / 'part.stl'
    source.write_text('solid x\nfacet normal 0 0 0\nouter loop\nvertex 0 0 0\nvertex 1 0 0\nvertex 0 1 0\nendloop\nendfacet\nendsolid x\n')
    return source


def _allow_post(monkeypatch):
    from print_buddy.core import slice_guard
    monkeypatch.setattr(adapter, 'pre_slice', lambda **kwargs: slice_guard.Result())
    monkeypatch.setattr(adapter, 'post_slice', lambda *_args, **_kwargs: slice_guard.Result())
    monkeypatch.setattr(adapter.sg, 'enforce_approved_baseline', lambda *_args: slice_guard.Result())
    monkeypatch.setattr(adapter, 'finalize_zmod', lambda *_args: None)


def test_orca_adapter_pre_slice_guard_blocks_before_orca_invocation(tmp_path, monkeypatch):
    from print_buddy.core import slice_guard
    monkeypatch.setattr(adapter, 'pre_slice', lambda **kwargs: slice_guard.Result(status='blocked', blocked=['test block']))
    with patch.object(adapter.subprocess, 'run') as run:
        try:
            adapter.slice_model(_source(tmp_path), tmp_path/'out', _state())
        except RuntimeError as exc:
            assert 'test block' in str(exc)
        else:
            raise AssertionError('blocked pre-slice guard was ignored')
        run.assert_not_called()


def test_auto_scaled_stl_with_copies_exports_distinct_geometry(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    source = _source(tmp_path)
    calls = []

    def run(command, **_kwargs):
        calls.append(command)
        mesh = Path(command[-1]).read_bytes()
        triangles = struct.unpack('<I', mesh[80:84])[0]
        assert triangles == 2
        output = Path(command[command.index('--outputdir') + 1]) / 'plate_1.gcode'
        output.write_text('; generated by OrcaSlicer 2.4.2\nG90\nG1 X1 Y1 Z0.2\nEND_PRINT\n')
        return type('R', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()

    monkeypatch.setattr(adapter.subprocess, 'run', run)
    output, _provenance, _configs = adapter.slice_model(source, tmp_path / 'out', _state(), scale=25.4, copies=2)
    assert output.is_file()
    assert len(calls) == 1


def test_bambu_runs_only_after_orca_execution_failure(tmp_path, monkeypatch):
    _allow_post(monkeypatch)
    calls = []

    def run(command, **_kwargs):
        calls.append(command)
        if 'com.orcaslicer.OrcaSlicer' in command:
            return type('R', (), {'returncode': 18, 'stdout': '', 'stderr': 'Orca exploded'})()
        assert command[:5] == ['flatpak', 'run', '--unshare=network', '--command=bambu-studio', 'com.bambulab.BambuStudio']
        output = Path(command[command.index('--outputdir') + 1]) / 'plate_1.gcode'
        output.write_text('; generated by BambuStudio 2.8.2\nG90\nG1 X1 Y1 Z0.2\nEND_PRINT\n')
        return type('R', (), {'returncode': 0, 'stdout': '', 'stderr': ''})()

    monkeypatch.setattr(adapter.subprocess, 'run', run)
    output, provenance, configs = adapter.slice_model(_source(tmp_path), tmp_path / 'out', _state())
    assert output.is_file()
    assert len(calls) == 2
    assert provenance['slicer'] == 'Bambu Studio'
    assert provenance['fallback']['from'] == 'OrcaSlicer'
    assert 'Orca slicing failed (18)' in provenance['fallback']['reason']
    assert any(path.name == 'machine.json' and path.parent.name == 'bambu' for path in configs)


