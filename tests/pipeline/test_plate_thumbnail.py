"""Plate previews for the Bambu package (#275): Orca's embedded thumbnail first, else an offline render.

Offline: no slicer, no OpenSCAD, no printer. The G-code blocks are synthetic in Orca's syntax.
"""
import base64
import io
import struct

import numpy as np
from PIL import Image

from print_buddy.core import plate_thumbnail as pt


def _png(width, height, colour=(200, 30, 30, 255)):
    buffer = io.BytesIO()
    Image.new('RGBA', (width, height), colour).save(buffer, format='PNG')
    return buffer.getvalue()


def _orca_block(png, width, height):
    data = base64.b64encode(png).decode()
    lines = '\n'.join('; ' + data[i:i + 78] for i in range(0, len(data), 78))
    return f'; THUMBNAIL_BLOCK_START\n; thumbnail begin {width}x{height} {len(data)}\n{lines}\n; thumbnail end\n; THUMBNAIL_BLOCK_END\n'


def box_stl(path, x=20.0, y=10.0, z=5.0, origin=(0.0, 0.0, 0.0)):
    """A closed binary STL box with its corner at origin."""
    ox, oy, oz = origin
    v = [(ox, oy, oz), (ox + x, oy, oz), (ox + x, oy + y, oz), (ox, oy + y, oz),
         (ox, oy, oz + z), (ox + x, oy, oz + z), (ox + x, oy + y, oz + z), (ox, oy + y, oz + z)]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    with open(path, 'wb') as out:
        out.write(b'\0' * 80 + struct.pack('<I', len(faces)))
        for a, b, c in faces:
            out.write(struct.pack('<12fH', 0, 0, 0, *v[a], *v[b], *v[c], 0))
    return path


def test_embedded_thumbnails_are_parsed_largest_first_and_bad_blocks_skipped():
    small, large = _png(16, 16), _png(300, 300)
    text = ('; generated by OrcaSlicer 2.4.2\n' + _orca_block(small, 16, 16) + _orca_block(large, 300, 300) +
            '; thumbnail begin 10x10 4\n; !!!!\n; thumbnail end\n'            # not base64
            '; thumbnail begin 10x10 8\n; aGVsbG8=\n; thumbnail end\n'        # base64 but not a PNG
            'G90\nG1 X1\n')
    found = pt.embedded_thumbnails(text)
    assert [(w, h) for w, h, _ in found] == [(300, 300), (16, 16)]
    assert found[0][2] == large and found[1][2] == small
    assert pt.embedded_thumbnails('; generated by OrcaSlicer 2.4.2\nG90\n') == []


def test_render_plate_draws_the_model_on_the_bed_as_a_square_rgba_png(tmp_path):
    from print_buddy.core.orca_adapter import source_triangles
    triangles = source_triangles(box_stl(tmp_path / 'box.stl', origin=(118, 123, 0)))
    for top in (False, True):
        image = Image.open(io.BytesIO(pt.render_plate(triangles, 256, (256, 256), top=top)))
        assert image.size == (256, 256) and image.mode == 'RGBA'
        pixels = np.asarray(image).reshape(-1, 4)
        assert (pixels[:, 3] == 0).any()                                            # transparent background
        assert ((pixels[:, 2] > pixels[:, 0]) & (pixels[:, 3] == 255)).sum() > 20   # the blue model
    bed_grey = np.array([214, 218, 224, 255])
    with_bed = np.asarray(Image.open(io.BytesIO(pt.render_plate(triangles, 64, (256, 256))))).reshape(-1, 4)
    without = np.asarray(Image.open(io.BytesIO(pt.render_plate(triangles, 64)))).reshape(-1, 4)
    assert (with_bed == bed_grey).all(axis=1).any() and not (without == bed_grey).all(axis=1).any()


def test_plate_thumbnails_prefer_the_gcode_thumbnail_then_a_render_then_nothing(tmp_path):
    gcode = tmp_path / 'plate_1.gcode'
    gcode.write_text('; generated by OrcaSlicer 2.4.2\n' + _orca_block(_png(140, 110), 140, 110) + 'G90\n')
    found = pt.plate_thumbnails(gcode)
    assert found.source == 'Orca thumbnail 140x110 embedded in the G-code'
    assert set(found.images) == {'plate', 'plate_small'}
    assert Image.open(io.BytesIO(found.images['plate'])).size == (512, 512)
    assert Image.open(io.BytesIO(found.images['plate_small'])).size == (128, 128)

    gcode.write_text('; generated by OrcaSlicer 2.4.2\nG90\nG1 X1\n')
    assert pt.plate_thumbnails(gcode).images == {}
    box_stl(tmp_path / 'geometry.stl')
    rendered = pt.plate_thumbnails(gcode, bed_mm=(220, 220))
    assert rendered.source == 'rendered from geometry.stl' and set(rendered.images) == {'plate', 'plate_small'}
    assert Image.open(io.BytesIO(rendered.images['plate'])).size == (512, 512)


def test_geometry_candidates_follow_the_recorded_slicer_input_before_the_folder(tmp_path):
    gcode = tmp_path / 'plate_1.gcode'
    gcode.write_text('G90\n')
    assert pt.geometry_candidates(gcode) == []
    (tmp_path / 'source').mkdir()
    source = box_stl(tmp_path / 'source' / 'model.stl')
    assert pt.geometry_candidates(gcode, {'downloaded_file': str(source)}) == [source]
    placed = box_stl(tmp_path / 'geometry.stl')
    assert pt.geometry_candidates(gcode, {'downloaded_file': str(source)}) == [placed, source]
    (tmp_path / 'input').mkdir()
    exact = box_stl(tmp_path / 'input' / 'placed.stl')
    job = {'gcode': str(gcode), 'provenance': {'slicer_command': ['orca', '--slice', '0', str(exact)]},
           'downloaded_file': str(source)}
    assert pt.geometry_candidates(gcode, job) == [exact, placed, source]
    derived = {'derived_plates': [{'gcode': str(gcode), 'provenance': {'slicer_command': ['orca', str(exact)]}}]}
    assert pt.geometry_candidates(gcode, derived) == [exact, placed]
    gone = {'gcode': str(gcode), 'provenance': {'slicer_command': ['orca', str(tmp_path / 'missing.3mf')]}}
    assert pt.geometry_candidates(gcode, gone) == [placed]


def test_a_candidate_without_triangles_is_skipped_for_the_next(tmp_path):
    import zipfile
    gcode = tmp_path / 'plate_1.gcode'
    gcode.write_text('G90\n')
    empty = tmp_path / 'ghost.3mf'
    with zipfile.ZipFile(empty, 'w') as archive:
        archive.writestr('3D/3dmodel.model', '<model/>')
    job = {'gcode': str(gcode), 'provenance': {'slicer_command': ['orca', str(empty)]}}
    assert pt.plate_thumbnails(gcode, job).images == {}
    box_stl(tmp_path / 'geometry.stl')
    assert pt.plate_thumbnails(gcode, job).source == 'rendered from geometry.stl'
