"""Orca inputs per printer model, pinned against golden JSON.

Slices two corpus models for the AD5X and the SV06 with subprocess.run mocked, and records what Orca would
receive: the machine, process and filament JSON, the argv, and the settings the printer contributes.
Paths are normalized. Regenerate on purpose with PRINT_BUDDY_WRITE_GOLDEN=1 and review the diff.
"""
import copy
import json
import os
from pathlib import Path

import pytest

from print_buddy import printers, settings
from print_buddy.core import orca_adapter, slice_guard

ROOT = Path(__file__).resolve().parents[2]
GOLDEN = Path(__file__).parent / "golden"
STATE = ROOT / "tests" / "pipeline" / "fixtures" / "printer_hardware.json"
CASES = ROOT / "tests" / "corpus" / "cases"
MODELS = {"ad5x": "flashforge.ad5x", "sv06": "sovol.sv06"}
SOURCES = {"single-part": {}, "parts-one-plate": {"copies": 2}}
# Identity keys that legitimately changed with the refactor (family became model, per-model names), and
# the vendor profile's identity and slicer choice (not Orca inputs; the argv below pins the slicer).
IDENTITY = ("family", "model", "name", "firmware", "vendor", "slicer")
# The AD5X start/end live in its Orca template; its model file now names them START_PRINT/END_PRINT (nothing reads them).
UNUSED = {"ad5x": ("start_macro", "end_macro")}
SECTIONS = ("printer", "layout", "prime_tower", "cold_pull")


def adapter_for(name):
    return printers.get(MODELS[name], settings.load(local=False, environ={"PRINT_BUDDY__PRINTER__MODEL": MODELS[name]}))


def capture(name, case, tmp_path, monkeypatch, **kw):
    baselines = []
    # A machine's YAML or TOML local config may point at another slicer; the golden argv is the home command.
    monkeypatch.setattr(orca_adapter, "ORCA_COMMAND", list(settings.load(local=False, environ={})["orca"]["command"]))
    monkeypatch.setattr(orca_adapter, "pre_slice", lambda **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter, "post_slice", lambda *a, **k: slice_guard.Result())
    monkeypatch.setattr(orca_adapter.sg, "enforce_approved_baseline",
                        lambda out, **k: baselines.append(str(k.get("path", "default"))) or slice_guard.Result())
    calls = []

    def run(command, **_kwargs):
        calls.append(list(command))
        out = Path(command[command.index("--outputdir") + 1]) / "plate_1.gcode"
        out.write_text("; generated by OrcaSlicer 2.4.2\nM104 S0\nG90\nG1 X1 Y1 Z0.2 E1\nEND_PRINT\n" * 40)
        return type("R", (), {"returncode": 0, "stdout": "", "stderr": ""})()

    monkeypatch.setattr(orca_adapter.subprocess, "run", run)
    state = copy.deepcopy(json.loads(STATE.read_text()))
    state["ifs_slots"] = {"1": {"slot": 1, "spoolman_id": 10, "material": "PLA", "physical_color_verified": True,
                                "hex": "FFFFFF"}}
    folder = tmp_path / name
    adapter = adapter_for(name)
    output, _prov, _ = orca_adapter.slice_model(CASES / case / "model.3mf", folder, state, adapter=adapter, **kw)

    def norm(text):
        return text.replace(str(folder), "<out>").replace(str(CASES / case), "<case>").replace(str(ROOT), "<repo>")

    cfg = adapter.config
    return {
        "machine": json.loads((folder / "machine.json").read_text()),
        "process": json.loads((folder / "process.json").read_text()),
        "filament": json.loads((folder / "filament.json").read_text()),
        "argv": [norm(a) for a in calls[0]],
        "baseline_is_shared_file": [b == "default" for b in baselines],
        "gcode": norm(output.read_text()),
        "settings": {s: {k: v for k, v in json.loads(json.dumps(cfg[s], default=str)).items() if k not in IDENTITY}
                     for s in SECTIONS},
        "slot_count": adapter.slot_count,
        "start_plan": adapter.start_plan(60, 215),
    }


@pytest.mark.parametrize("name", list(MODELS))
@pytest.mark.parametrize("case", list(SOURCES))
def test_orca_inputs_match_golden(name, case, tmp_path, monkeypatch):
    got = capture(name, case, tmp_path, monkeypatch, **SOURCES[case])
    path = GOLDEN / f"{name}__{case}.json"
    if os.environ.get("PRINT_BUDDY_WRITE_GOLDEN"):
        path.write_text(json.dumps(got, indent=2, sort_keys=True) + "\n")
    want = json.loads(path.read_text())
    for data in (got, want):
        for key in UNUSED.get(name, ()):
            data["settings"]["printer"].pop(key, None)
    assert got == want
